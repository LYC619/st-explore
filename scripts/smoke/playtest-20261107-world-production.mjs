import { chromium, expect } from '@playwright/test';
import { preview } from 'vite';
import { writeFile, mkdir } from 'node:fs/promises';
const out = '.cache/play-world-b25-production'; await mkdir(out, { recursive: true });
const server = await preview({ configFile: false, preview: { host: '127.0.0.1', port: 4229, strictPort: true } });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [], sourceRequests = [], workerRequests = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', req => { if (req.url().includes('/src/')) sourceRequests.push(req.url()); if (/simulation.worker/.test(req.url())) workerRequests.push(req.url()); });
try {
  await page.goto('http://127.0.0.1:4229/play');
  await page.getByRole('button', { name: /原生世界 · 无需模型/ }).click();
  await page.getByRole('button', { name: '开辟新世界', exact: true }).click();
  await page.getByRole('button', { name: '启程', exact: true }).click();
  await expect(page.getByTestId('world-tick')).toContainText('第 0 步');
  await page.getByRole('button', { name: '干预', exact: true }).click();
  await page.getByRole('button', { name: '确认并推进', exact: true }).click();
  await expect(page.getByTestId('world-tick')).toContainText('第 1 步');
  await expect(page.getByLabel('追踪人物摘要')).toContainText('暴雨封渡');
  await page.reload(); await expect(page.getByTestId('world-tick')).toContainText('第 1 步');
  await page.getByRole('button', { name: '推进一步', exact: true }).click(); await expect(page.getByTestId('world-tick')).toContainText('第 2 步');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: '推进一步', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.getByRole('button', { name: '接管追踪人物冒险', exact: true }).click();
  await expect(page.getByLabel('玩家冒险')).toBeVisible();
  await page.screenshot({ path: `${out}/adventure-mobile.png` });
  await page.reload(); await expect(page.getByLabel('玩家冒险')).toBeVisible();
  await page.getByRole('button', { name: '回到观赏', exact: true }).click();
  await page.getByRole('button', { name: '返回世界列表', exact: true }).click();
  await page.getByLabel('导入世界备份文件').setInputFiles('.cache/play-world-b25-recovery/full.ste-world');
  await expect(page).toHaveURL(/\/gal\//);
  await expect(page.locator('.gal-background[src^="blob:"]')).toBeVisible();
  await expect(page.getByRole('heading', { name: '素材与断点' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.setViewportSize({ width: 390, height: 480 });
  await expect(page.getByRole('button', { name: '剧场行囊', exact: true })).toBeInViewport();
  await page.screenshot({ path: `${out}/gal-short.png` });
  await page.reload(); await expect(page.locator('.gal-background[src^="blob:"]')).toBeVisible();
  await page.getByRole('button', { name: '剧情回顾', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible(); await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: `${out}/gal-desktop.png` });
  await page.getByRole('button', { name: '离开剧场', exact: true }).click();
  await expect(page).toHaveURL(/\/worlds$/);
  expect(errors).toEqual([]); expect(sourceRequests).toEqual([]); expect(workerRequests.length).toBeGreaterThan(0);
  await writeFile(`${out}/result.json`, JSON.stringify({ errors, sourceRequests, workerRequests, result: '最终dist入口、Worker、干预、接管重开、完整GAL包/素材/历史/返回及390px短视口通过' }, null, 2));
  console.log('production: entry, worker, adventure, GAL package/assets/reopen/history, 390px/short viewport passed');
} finally { await browser.close(); await new Promise(resolve => server.httpServer.close(resolve)); }
